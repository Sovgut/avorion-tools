// Collects the game scripts that galaxy generation runs and compiles them into one JS module.
import luaparse from 'luaparse';
import { Compiler, runtimeImportNames } from '../src/engine/lua/compiler';
import type { GameFiles } from './game';

/** Scripts the generator calls into directly; their includes are followed transitively. */
export const GENERATION_ENTRIES = [
  'data/scripts/sectorspecifics.lua',
  'data/scripts/lib/factorypredictor.lua',
  'data/scripts/lib/factionsmap.lua',
  'data/scripts/lib/passagemap.lua',
  'data/scripts/lib/goods.lua',
  'data/scripts/lib/productions.lua',
  'data/scripts/lib/plangeneratorbase.lua',
];

const INCLUDE_RE = /\b(?:include|require)\s*\(?\s*["']([^"']+)["']/g;
const TEMPLATE_RE = /\baddTemplate\s*\(\s*["']([^"']+)["']/g;

export interface ScriptClosure {
  files: string[];
  /** include() names that point at files the game ships only in encrypted form. */
  unresolved: { name: string; from: string }[];
}

export function collectClosure(game: GameFiles, entries: string[]): ScriptClosure {
  const seen = new Set<string>();
  const unresolved: { name: string; from: string }[] = [];
  const visit = (rel: string) => {
    if (seen.has(rel)) return;
    seen.add(rel);
    const src = game.readBytes(rel);
    for (const re of [INCLUDE_RE, TEMPLATE_RE]) {
      re.lastIndex = 0;
      for (let m = re.exec(src); m; m = re.exec(src)) {
        const target = game.resolveInclude(m[1]);
        if (target) visit(target);
        else unresolved.push({ name: m[1], from: rel });
      }
    }
  };
  for (const e of entries) visit(e);
  return { files: [...seen].sort(), unresolved };
}

/** An ES module exporting `modules`: path → (runtime) => chunk function. */
export function compileBundle(game: GameFiles, files: string[], header: string): string {
  const parts: string[] = [];
  parts.push(`// ${header}`);
  parts.push('// Generated by `npm run analyze`. Do not edit.');
  parts.push('/* eslint-disable */');
  parts.push(`const RT = ${JSON.stringify([...runtimeImportNames])};`);
  parts.push('export const modules = {');
  for (const f of files) {
    const js = new Compiler({ chunkName: f }).compileChunk(game.readBytes(f));
    parts.push(`${JSON.stringify(f)}: (R) => { const { ${runtimeImportNames.join(', ')} } = R; return ${js}; },`);
  }
  parts.push('};');
  parts.push('export const runtimeNames = RT;');
  return parts.join('\n');
}

export const BUNDLE_DTS = `// Generated by \`npm run analyze\`. Do not edit.
import type { ModuleFactory } from '../engine/lua/rt';
export declare const modules: Record<string, ModuleFactory>;
export declare const runtimeNames: string[];
`;

/** Global names the scripts read but never assign: the natives they expect the engine to provide. */
export function findNativeReferences(game: GameFiles, files: string[]): string[] {
  const reads = new Set<string>();
  const writes = new Set<string>();
  for (const f of files) {
    const ast = luaparse.parse(game.readBytes(f), { luaVersion: '5.2', scope: true, encodingMode: 'pseudo-latin1' } as any);
    const visit = (n: any, key?: string, parent?: any) => {
      if (!n || typeof n !== 'object') return;
      if (Array.isArray(n)) {
        for (const x of n) visit(x, key, parent);
        return;
      }
      if (
        n.type === 'Identifier' &&
        !n.isLocal &&
        !(parent?.type === 'MemberExpression' && key === 'identifier') &&
        !(parent?.type === 'TableKeyString' && key === 'key') &&
        parent?.type !== 'LabelStatement' &&
        parent?.type !== 'GotoStatement'
      ) {
        const isWrite = (parent?.type === 'AssignmentStatement' && key === 'variables') || (parent?.type === 'FunctionDeclaration' && key === 'identifier');
        (isWrite ? writes : reads).add(n.name);
      }
      for (const k of Object.keys(n)) if (k !== 'loc' && k !== 'globals') visit(n[k], k, n);
    };
    visit(ast);
  }
  return [...reads].filter((n) => !writes.has(n)).sort();
}
